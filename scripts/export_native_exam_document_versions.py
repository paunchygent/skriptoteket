"""Export the native exam document format constants for the browser.

The browser reads the native exam document format constants from one source:
this script renders them from the Python domain truth into
``frontend/apps/skriptoteket/src/api/nativeExamDocumentVersions.generated.ts``.
The backend drift test fails when the committed file differs from the
rendered output, so bumping the Python constants requires regenerating.
"""

from __future__ import annotations

from pathlib import Path


def _repo_root() -> Path:
    return Path(__file__).resolve().parents[1]


def native_exam_document_schema_prefix(*, schema_version: str, current_version: int) -> str:
    """The version-less prefix of the current schema version token.

    The domain owns no separate prefix constant; the prefix is the schema
    version token without its trailing current version number.
    """
    suffix = str(current_version)
    if not schema_version.endswith(suffix):
        raise RuntimeError(
            "NATIVE_EXAM_DOCUMENT_SCHEMA_VERSION does not end with "
            f"the current version: {schema_version!r} / {current_version!r}."
        )
    prefix = schema_version[: -len(suffix)]
    if prefix + suffix != schema_version:
        raise RuntimeError(f"Cannot split the schema version token: {schema_version!r}.")
    return prefix


def render_native_exam_document_versions(
    *,
    prefix: str,
    current_version: int,
    oldest_readable_version: int,
) -> str:
    """Render the generated TypeScript module from the domain constants."""
    lines = [
        "// Generated by scripts/export_native_exam_document_versions.py"
        " from native_exam_document_versions.py; do not edit.",
        f'export const NATIVE_EXAM_DOCUMENT_SCHEMA_PREFIX = "{prefix}";',
        f"export const CURRENT_NATIVE_EXAM_DOCUMENT_VERSION = {current_version};",
        f"export const OLDEST_READABLE_NATIVE_EXAM_DOCUMENT_VERSION = {oldest_readable_version};",
    ]
    return "\n".join(lines) + "\n"


def export_native_exam_document_versions(*, output_path: Path) -> None:
    src_dir = _repo_root() / "src"
    import sys

    if str(src_dir) not in sys.path:
        sys.path.insert(0, str(src_dir))

    from skriptoteket.domain.curated_apps.exam_workspace.native_exam_document_versions import (
        CURRENT_NATIVE_EXAM_DOCUMENT_VERSION,
        NATIVE_EXAM_DOCUMENT_SCHEMA_VERSION,
        OLDEST_READABLE_NATIVE_EXAM_DOCUMENT_VERSION,
    )

    prefix = native_exam_document_schema_prefix(
        schema_version=NATIVE_EXAM_DOCUMENT_SCHEMA_VERSION,
        current_version=CURRENT_NATIVE_EXAM_DOCUMENT_VERSION,
    )
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(
        render_native_exam_document_versions(
            prefix=prefix,
            current_version=CURRENT_NATIVE_EXAM_DOCUMENT_VERSION,
            oldest_readable_version=OLDEST_READABLE_NATIVE_EXAM_DOCUMENT_VERSION,
        ),
        encoding="utf-8",
    )


def main() -> None:
    output_path = (
        _repo_root()
        / "frontend"
        / "apps"
        / "skriptoteket"
        / "src"
        / "api"
        / "nativeExamDocumentVersions.generated.ts"
    )
    export_native_exam_document_versions(output_path=output_path)
    print(f"Wrote native exam document versions: {output_path}")


if __name__ == "__main__":
    main()
