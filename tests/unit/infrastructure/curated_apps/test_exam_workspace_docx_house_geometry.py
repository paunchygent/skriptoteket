ExamWorkspaceDocxWriter = exam_workspace_docx_writer.ExamWorkspaceDocxWriter

# One OOXML twip is the storage unit for page geometry and paragraph spacing, so a
# template millimetre comes back within one twip rather than bit-equal in EMU.
_TWIP_MM = 25.4 / 1440
_TOLERANCE_MM = _TWIP_MM * 1.01


def _parse(document: NativeExamDocument) -> DocxDocument:
    return Document(io.BytesIO(ExamWorkspaceDocxWriter().build_docx_bytes(document)))


def _assert_mm(actual_mm: float, expected_mm: float, tolerance_mm: float = _TOLERANCE_MM) -> None:
    assert actual_mm == pytest.approx(expected_mm, abs=tolerance_mm)


def _set(length: Length | None) -> Length:
    assert length is not None, "the house template sets this measure"
    return length


def _rfonts(style: ParagraphStyle):
    rFonts = style.element.get_or_add_rPr().find(qn("w:rFonts"))
    assert rFonts is not None
    return rFonts


def _assert_house_font(style: ParagraphStyle) -> None:
    rFonts = _rfonts(style)
    for attribute in ("ascii", "hAnsi", "eastAsia", "cs"):
        assert rFonts.get(qn(f"w:{attribute}")) == house_template.HOUSE_FONT_FAMILIES[0]
    for attribute in ("asciiTheme", "hAnsiTheme", "eastAsiaTheme", "cstheme"):
        assert rFonts.get(qn(f"w:{attribute}")) is None


@pytest.fixture(scope="module")
def parsed() -> DocxDocument:
    return _parse(all_kinds_document())


class TestPageGeometry:
    def test_every_section_is_a4_with_the_template_margins(self, parsed: DocxDocument) -> None:
        assert len(parsed.sections) == 1
        section = parsed.sections[0]

        _assert_mm(_set(section.page_width).mm, house_template.PAGE_WIDTH_MM)
        _assert_mm(_set(section.page_height).mm, house_template.PAGE_HEIGHT_MM)
        _assert_mm(_set(section.left_margin).mm, house_template.PAGE_MARGIN_SIDE_MM)
        _assert_mm(_set(section.right_margin).mm, house_template.PAGE_MARGIN_SIDE_MM)
        _assert_mm(_set(section.top_margin).mm, house_template.PAGE_MARGIN_VERTICAL_MM)
        _assert_mm(_set(section.bottom_margin).mm, house_template.PAGE_MARGIN_VERTICAL_MM)

        text_width = Emu(
            _set(section.page_width) - _set(section.left_margin) - _set(section.right_margin)
        )
        # Three independently rounded twip measures: allow the sum of their roundings.
        _assert_mm(text_width.mm, house_template.TEXT_WIDTH_MM, tolerance_mm=_TWIP_MM * 3)

    def test_the_page_is_not_word_s_letter_default(self, parsed: DocxDocument) -> None:
        section = parsed.sections[0]

        assert round(_set(section.page_width).mm, 1) != 215.9
        assert round(_set(section.page_height).mm, 1) != 279.4


class TestTextStyles:
    def test_normal_style_follows_the_template(self, parsed: DocxDocument) -> None:
        normal = parsed.styles["Normal"]

        assert normal.font.name == house_template.HOUSE_FONT_FAMILIES[0]
        assert normal.font.size == Pt(house_template.HOUSE_FONT_SIZE_PT)
        assert normal.font.color.rgb == RGBColor.from_string(house_template.TEXT_COLOR_HEX)
        assert normal.paragraph_format.line_spacing == house_template.HOUSE_LINE_HEIGHT
        _assert_mm(
            normal.paragraph_format.space_before.mm,
            house_template.PARAGRAPH_SPACING.space_before_mm,
        )
        _assert_mm(
            normal.paragraph_format.space_after.mm,
            house_template.PARAGRAPH_SPACING.space_after_mm,
        )
        _assert_house_font(normal)

    @pytest.mark.parametrize("level", sorted(house_template.HEADING_GEOMETRY))
    def test_built_in_heading_style_follows_the_template(
        self, parsed: DocxDocument, level: int
    ) -> None:
        geometry = house_template.HEADING_GEOMETRY[level]
        style = parsed.styles[f"Heading {level}"]

        # The style name stays the built-in one; validate_docx_bytes counts it.
        assert style.name == f"Heading {level}"
        assert style.font.name == house_template.HOUSE_FONT_FAMILIES[0]
        assert style.font.size == Pt(geometry.size_pt)
        assert style.font.bold is True
        assert style.font.italic is False
        assert style.font.color.rgb == RGBColor.from_string(house_template.TEXT_COLOR_HEX)
        _assert_mm(style.paragraph_format.space_before.mm, geometry.spacing.space_before_mm)
        _assert_mm(style.paragraph_format.space_after.mm, geometry.spacing.space_after_mm)
        assert style.paragraph_format.keep_with_next is True
        _assert_house_font(style)


class TestAnswerBoxes:
    def test_a_number_option_prints_a_bordered_empty_box_and_no_tick_glyph(self) -> None:
        parsed = _parse(make_document(make_ordering_item()))

        boxed = [
            paragraph
            for paragraph in parsed.paragraphs
            if paragraph.runs and run_border(paragraph.runs[0]) is not None
        ]
        assert len(boxed) == 4
        box_width = NBSP * math.ceil(
            house_template.NUMBER_BOX_WIDTH_MM / house_template.NBSP_WIDTH_MM
        )
        gap_width = NBSP * math.ceil(house_template.BOX_GAP_MM / house_template.NBSP_WIDTH_MM)
        expected_border = {
            "val": "single",
            "sz": str(round(house_template.BOX_BORDER_PT * 8)),
            "space": "0",
            "color": house_template.TEXT_COLOR_HEX,
        }
        for paragraph in boxed:
            box, gap, text = paragraph.runs

            assert box.text == box_width
            assert run_border(box) == expected_border
            assert gap.text == gap_width
            assert text.text in {"Avslutning", "Motargument", "Argument", "Tes"}
            assert house_template.TICK_BOX_GLYPH not in paragraph.text

    def test_a_tick_option_prints_the_glyph_as_its_own_run(self) -> None:
        parsed = _parse(make_document(make_single_choice_item()))

        paragraph = only_paragraph(
            list(parsed.paragraphs), f"{house_template.TICK_BOX_GLYPH} A) vägen"
        )

        assert run_shape(paragraph) == [house_template.TICK_BOX_GLYPH, " A) vägen"]
        assert run_border(paragraph.runs[0]) is None

    def test_tick_and_number_options_differ_in_their_first_run(self) -> None:
        ticks = _parse(make_document(make_single_choice_item()))
        numbers = _parse(make_document(make_ordering_item()))
        tick_run = only_paragraph(
            list(ticks.paragraphs), f"{house_template.TICK_BOX_GLYPH} A) vägen"
        ).runs[0]
        number_paragraph = next(
            paragraph
            for paragraph in numbers.paragraphs
            if paragraph.runs and run_border(paragraph.runs[0]) is not None
        )
        number_run = number_paragraph.runs[0]

        assert tick_run.text == house_template.TICK_BOX_GLYPH
        assert run_border(tick_run) is None
        assert number_run.text != house_template.TICK_BOX_GLYPH
        assert run_border(number_run) is not None


class TestGrid:
    def test_the_match_grid_uses_the_template_glyph_padding_and_zero_cell_spacing(self) -> None:
        parsed = _parse(make_document(matching_item()))

        assert len(parsed.tables) == 1
        table = parsed.tables[0]
        for row in table.rows[1:]:
            for cell in row.cells[1:]:
                assert cell.text == house_template.TICK_BOX_GLYPH

        margins = table._tbl.tblPr.find(qn("w:tblCellMar"))
        assert margins is not None
        padding = str(round(house_template.GRID_CELL_PADDING_MM * 1440 / 25.4))
        for edge in ("top", "left", "bottom", "right"):
            measure = margins.find(qn(f"w:{edge}"))
            assert measure is not None
            assert measure.get(qn("w:w")) == padding
            assert measure.get(qn("w:type")) == "dxa"

        for row in table.rows:
            for cell in row.cells:
                for paragraph in cell.paragraphs:
                    _assert_mm(paragraph.paragraph_format.space_before.mm, 0)
                    _assert_mm(paragraph.paragraph_format.space_after.mm, 0)

    def test_a_question_ending_in_a_grid_gets_a_spacer_with_the_grid_margins(self) -> None:
        parsed = _parse(make_document(matching_item()))

        spacer = parsed.paragraphs[-1]
        assert spacer.text == ""
        _assert_mm(
            spacer.paragraph_format.space_before.mm, house_template.GRID_SPACING.space_after_mm
        )
        _assert_mm(spacer.paragraph_format.space_after.mm, 0)
        assert spacer.paragraph_format.line_spacing_rule is WD_LINE_SPACING.EXACTLY
        _assert_mm(spacer.paragraph_format.line_spacing.mm, house_template.QUESTION_SPACE_AFTER_MM)

        before_table = parsed.paragraphs[-2]
        assert before_table.text == "Kategorisera orden i rätt ordklass. (3 p)"
        _assert_mm(
            before_table.paragraph_format.space_after.mm,
            house_template.GRID_SPACING.space_before_mm,
        )


class TestWritingArea:
    def test_the_first_and_last_ruled_lines_carry_the_writing_area_spacing(
        self, parsed: DocxDocument
    ) -> None:
        ruled = [
            paragraph for paragraph in parsed.paragraphs if border_edges(paragraph) is not None
        ]
        assert len(ruled) == 8

        _assert_mm(
            ruled[0].paragraph_format.space_before.mm,
            house_template.WRITING_AREA_SPACING.space_before_mm,
        )
        for line in ruled[1:]:
            _assert_mm(line.paragraph_format.space_before.mm, 0)
        # The area's own trailing margin is swallowed by the question's larger space after,
        # exactly as the print CSS's collapsed margins behave.
        _assert_mm(
            ruled[-1].paragraph_format.space_after.mm, house_template.QUESTION_SPACE_AFTER_MM
        )

    def test_the_inline_points_run_prints_plain(self, parsed: DocxDocument) -> None:
        stem = only_paragraph(list(parsed.paragraphs), "Resonera om bisatser. (4 p)")

        assert all(run.font.bold in (False, None) for run in stem.runs)


class TestEntrySpacing:
    def test_each_question_ends_with_the_template_question_space(
        self, parsed: DocxDocument
    ) -> None:
        tails = _question_tails(parsed)
        assert len(tails) == 4

        for tail in tails:
            _assert_mm(tail.paragraph_format.space_after.mm, house_template.QUESTION_SPACE_AFTER_MM)

    def test_the_header_instruction_ends_with_the_template_instruction_space(
        self, parsed: DocxDocument
    ) -> None:
        first_question = next(
            index
            for index, paragraph in enumerate(parsed.paragraphs)
            if paragraph.style is not None and paragraph.style.name == "Heading 3"
        )
        header_tail = parsed.paragraphs[first_question - 1]

        assert header_tail.text == "Total: 9,5 poäng"
        _assert_mm(
            header_tail.paragraph_format.space_after.mm,
            house_template.INSTRUCTION_SPACE_AFTER_MM,
        )


def _question_tails(parsed: DocxDocument) -> list[Paragraph]:
    """Each question's last paragraph: the paragraph before the next Heading 3 or the end."""
    headings = [
        index
        for index, paragraph in enumerate(parsed.paragraphs)
        if paragraph.style is not None and paragraph.style.name == "Heading 3"
    ]
    tails: list[Paragraph] = []
    for position, start in enumerate(headings):
        end = headings[position + 1] if position + 1 < len(headings) else len(parsed.paragraphs)
        tails.append(parsed.paragraphs[end - 1])
    return tails
