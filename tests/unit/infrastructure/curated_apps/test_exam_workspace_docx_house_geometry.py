"""The DOCX student copy applies the one house template's geometry (TASK-SKRIPT-40-04-07 R1).

Every printed dimension comes from ``exam_print_house_template``: the A4 page and its
margins, the ``Normal`` and built-in heading styles, the writing area, the answer boxes,
the grid, and each entry's closing space. These tests read the generated bytes back with
python-docx and inspect the paragraph and run XML, so python-docx's own default Letter
page and theme heading styles cannot come back unnoticed.
"""

