"""Static Swedish and English misspelling data for the answer-misspelling producer.

Payloads are generated by ``scripts/build_answer_misspellings.py``; see ``ATTRIBUTION.md``
beside this module for sources, licences, pinned revisions and checksums.  The
data is loaded lazily from the package directory, uses the standard library
only, and never touches the network.

``rep`` entries are ``(wrong, right)`` pairs: ``right`` is the pattern that
appears in a correctly spelled answer and ``wrong`` is the attested misspelling
pattern to substitute for it. The tuple keeps the hunspell ``.aff`` column
order (misspelled, correction); generation applies the correction column in
reverse to produce the misspelling.
"""

from __future__ import annotations

import gzip
import json
from array import array
from dataclasses import dataclass
from functools import lru_cache
from importlib.resources import files
from threading import Lock
from types import MappingProxyType
from typing import Literal, Mapping

Language = Literal["sv", "en"]

_SUPPORTED_LANGUAGES: tuple[str, ...] = ("sv", "en")
_LOAD_LOCK = Lock()


@dataclass(frozen=True, slots=True)
class WordFormLexicon:
    """Case-folded membership test over a sorted, newline-separated word list.

    The word list stays as one decompressed byte blob plus 32-bit line-start
    offsets, so a full inflection set costs a few megabytes instead of a Python
    set of hundreds of thousands of strings.  Lookups are binary searches.
    """

    forms: bytes
    starts: array

    def __contains__(self, text: object) -> bool:
        if not isinstance(text, str):
            return False
        key = text.casefold().strip().encode("utf-8")
        if not key:
            return False
        starts = self.starts
        low = 0
        high = len(starts)
        while low < high:
            middle = (low + high) // 2
            start = starts[middle]
            end = starts[middle + 1] - 1 if middle + 1 < len(starts) else len(self.forms)
            current = self.forms[start:end]
            if current < key:
                low = middle + 1
            elif current > key:
                high = middle
            else:
                return True
        return False

    def contains(self, text: str) -> bool:
        """Return whether ``text`` case-folds to a listed valid word form."""
        return text in self


@dataclass(frozen=True, slots=True)
class LanguageMisspellingData:
    """One language's attested pairs, REP rules, keyboard map and word forms."""

    language: str
    attested: Mapping[str, tuple[str, ...]]
    rep: tuple[tuple[str, str], ...]
    keyboard: Mapping[str, tuple[str, ...]]
    valid_words: WordFormLexicon


def _decode_lexicon(payload: bytes) -> WordFormLexicon:
    forms = gzip.decompress(payload)
    if forms.endswith(b"\n"):
        forms = forms[:-1]
    starts = array("I", [0])
    for index, byte in enumerate(forms):
        if byte == 0x0A:
            starts.append(index + 1)
    return WordFormLexicon(forms=forms, starts=starts)


def load_misspelling_data(language: Language) -> LanguageMisspellingData:
    """Load one language's committed data once per process.

    Raises:
        ValueError: when ``language`` is not ``"sv"`` or ``"en"``.
    """
    if language not in _SUPPORTED_LANGUAGES:
        supported = ", ".join(_SUPPORTED_LANGUAGES)
        raise ValueError(f"unsupported misspelling language {language!r}; expected {supported}")
    # lru_cache alone permits duplicate first loads in simultaneous request threads.
    with _LOAD_LOCK:
        return _load_language_data(language)


@lru_cache(maxsize=2)
def _load_language_data(language: Language) -> LanguageMisspellingData:
    root = files(__package__)
    document = json.loads(root.joinpath(f"{language}.json").read_text(encoding="utf-8"))
    return LanguageMisspellingData(
        language=language,
        attested=MappingProxyType(
            {key: tuple(values) for key, values in document["attested"].items()}
        ),
        rep=tuple((wrong, right) for wrong, right in document["rep"]),
        keyboard=MappingProxyType(
            {key: tuple(values) for key, values in document["keyboard"].items()}
        ),
        valid_words=_decode_lexicon(root.joinpath(f"{language}_words.txt.gz").read_bytes()),
    )
