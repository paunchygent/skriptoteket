"""python-docx writer for the native exam workspace document (D3 export).

Renders a native exam document as a Word export written in the exam's own language
(TASK-SKRIPT-39-05-03 D21): title, instructions,
each parent's instruction once before its first child, one Heading 3 section per item
with body, points, choices and match lists, plus a final
answer-key section for keyed items ("Facit" or "Answer key"). Shared instruction bodies
embed every picture from the caller's stored payloads at its exact place; item bodies keep
their plain-text rendering. ``validate_docx_bytes`` re-opens the generated bytes and fails
closed before the artifact is handed out.
"""

import io
import zipfile
from collections.abc import Iterable, Mapping
from types import MappingProxyType

from docx import Document
from docx.document import Document as DocxDocument
from docx.opc.exceptions import PackageNotFoundError

from skriptoteket.domain.curated_apps.exam_workspace.exam_export_header import (
    exam_export_header_lines,
)
from skriptoteket.domain.curated_apps.exam_workspace.exam_language_labels import (
    ExamLanguageLabels,
    exam_language_labels,
)
from skriptoteket.domain.curated_apps.exam_workspace.native_exam_body import (
    NativeAssetSegment,
    NativeGapSegment,
    NativeParagraph,
    NativeTextSegment,
)
from skriptoteket.domain.curated_apps.exam_workspace.native_exam_document import (
    NativeExamDocument,
)
from skriptoteket.domain.curated_apps.exam_workspace.native_exam_item import (
    NativeExamItem,
)
from skriptoteket.domain.curated_apps.exam_workspace.native_exam_vocabulary import (
    NativeExamItemKind,
)
from skriptoteket.domain.curated_apps.exam_workspace.shared_body import body_plain_text
from skriptoteket.domain.errors import DomainError, ErrorCode

_ITEM_HEADING_STYLE = "Heading 3"
_CHOICE_KINDS = (
    NativeExamItemKind.SINGLE_CHOICE,
    NativeExamItemKind.MULTIPLE_RESPONSE,
)
_GAP_MARKER = "[___]"
NO_DOCX_EXPORT_ASSETS: Mapping[str, bytes] = MappingProxyType({})


def _write_shared_body(
    output: DocxDocument,
    body: Iterable[NativeParagraph],
    *,
    assets_by_id: Mapping[str, bytes],
) -> None:
    """One shared instruction body with text and pictures at their exact source places.

    Every text segment becomes its own run and every picture is embedded from the stored
    payload into the run that stands at that place, so a shared diagram keeps the order the
    teacher saw. A referenced picture without a stored payload is reported, never dropped.
    """
    for paragraph in body:
        target = output.add_paragraph()
        for segment in paragraph.segments:
            if isinstance(segment, NativeTextSegment):
                target.add_run(segment.text)
            elif isinstance(segment, NativeAssetSegment):
                payload = assets_by_id.get(segment.asset_id)
                if payload is None:
                    raise DomainError(
                        code=ErrorCode.VALIDATION_ERROR,
                        message="Word-exporten saknar bilddata för en bild i en delad instruktion.",
                        details={"asset_ids": [segment.asset_id]},
                    )
                target.add_run().add_picture(io.BytesIO(payload))
            else:
                target.add_run(_GAP_MARKER)


class ExamWorkspaceDocxWriter:
    """Deterministic DOCX export via python-docx."""

    def build_docx_bytes(
        self,
        document: NativeExamDocument,
        *,
        assets_by_id: Mapping[str, bytes] = NO_DOCX_EXPORT_ASSETS,
    ) -> bytes:
        labels = exam_language_labels(document)
        output = Document()
        title, *header_details = exam_export_header_lines(document)
        output.add_heading(title, level=1)
        for line in header_details:
            output.add_paragraph(line)
        _write_shared_body(output, document.instructions, assets_by_id=assets_by_id)

        for item in document.items:
            parent = document.parent_of(item.item_id)
            if parent is not None and parent.item_ids[0] == item.item_id:
                _write_shared_body(output, parent.instruction, assets_by_id=assets_by_id)
            output.add_heading(labels.item_title(item), level=3)
            for line in _item_text_lines(item):
                output.add_paragraph(line)
            output.add_paragraph(_points_line(item, labels))
            if item.kind in _CHOICE_KINDS:
                for index, choice in enumerate(item.choices):
                    output.add_paragraph(f"{_choice_letter(index)}) {body_plain_text(choice.body)}")
            for index, left in enumerate(item.match_left, start=1):
                output.add_paragraph(f"{index}. {body_plain_text(left.body)}")
            for index, right in enumerate(item.match_right):
                output.add_paragraph(f"{_choice_letter(index)}) {body_plain_text(right.body)}")

        keyed_items = tuple(item for item in document.items if _facit_lines(item, labels))
        if keyed_items:
            output.add_heading(labels.answer_key, level=2)
            for item in keyed_items:
                output.add_paragraph(labels.item_title(item))
                for line in _facit_lines(item, labels):
                    output.add_paragraph(line)

        buffer = io.BytesIO()
        output.save(buffer)
        return buffer.getvalue()

    def validate_docx_bytes(self, content: bytes, *, expected_item_count: int) -> None:
        """Fail-closed D3 validation: the export must re-open and keep all items."""
        try:
            parsed = Document(io.BytesIO(content))
        except (
            PackageNotFoundError,
            zipfile.BadZipFile,
            KeyError,
            ValueError,
        ) as error:
            raise DomainError(
                code=ErrorCode.VALIDATION_ERROR,
                message="Det genererade Word-dokumentet kunde inte läsas.",
            ) from error
        heading_count = sum(
            1
            for paragraph in parsed.paragraphs
            if paragraph.style is not None and paragraph.style.name == _ITEM_HEADING_STYLE
        )
        if heading_count != expected_item_count:
            raise DomainError(
                code=ErrorCode.VALIDATION_ERROR,
                message="Det genererade Word-dokumentet saknar förväntade frågerubriker.",
                details={
                    "expected_item_count": expected_item_count,
                    "found_item_headings": heading_count,
                },
            )


def _item_text_lines(item: NativeExamItem) -> tuple[str, ...]:
    if item.kind is not NativeExamItemKind.INLINE_CHOICE:
        return item.plain_text_lines()
    gaps = {gap.gap_id: gap for gap in item.gaps}
    lines: list[str] = []
    for paragraph in item.body:
        parts: list[str] = []
        for segment in paragraph.segments:
            if isinstance(segment, NativeTextSegment):
                parts.append(segment.text)
            elif isinstance(segment, NativeGapSegment):
                options = " / ".join(
                    body_plain_text(option.body) for option in gaps[segment.gap_id].options
                )
                parts.append(f"[{options}]")
        lines.append("".join(parts))
    return tuple(lines)


def _points_line(item: NativeExamItem, labels: ExamLanguageLabels) -> str:
    return labels.points_line(None if item.points is None else _format_points(item.points))


def _format_points(points: int | float) -> str:
    if isinstance(points, int) or float(points).is_integer():
        return str(int(points))
    return str(points).replace(".", ",")


def _choice_letter(index: int) -> str:
    if index < 26:
        return chr(ord("A") + index)
    return str(index + 1)


def _facit_lines(item: NativeExamItem, labels: ExamLanguageLabels) -> tuple[str, ...]:
    if item.kind is NativeExamItemKind.FREE_TEXT:
        if not item.criteria:
            return ()
        return (
            f"{labels.marking_guide}:",
            *(f"• {criterion.text} ({criterion.points} p)" for criterion in item.criteria),
        )
    if item.kind in _CHOICE_KINDS and item.answer_key.correct_choice_ids:
        text_by_choice_id = {
            choice.choice_id: body_plain_text(choice.body) for choice in item.choices
        }
        correct_texts = tuple(
            text_by_choice_id[choice_id] for choice_id in item.answer_key.correct_choice_ids
        )
        return (labels.keyed(labels.correct_answer, "; ".join(correct_texts)),)
    if item.kind is NativeExamItemKind.GAP_FILL and any(gap.accepted_values for gap in item.gaps):
        return tuple(
            labels.keyed(labels.gap_label(index), " / ".join(gap.accepted_values))
            for index, gap in enumerate(item.gaps, start=1)
        )
    if item.kind is NativeExamItemKind.INLINE_CHOICE:
        return tuple(
            labels.keyed(
                labels.gap_label(index),
                body_plain_text(
                    next(
                        option.body
                        for option in gap.options
                        if option.choice_id == gap.correct_option_id
                    )
                ),
            )
            for index, gap in enumerate(item.body_gaps(), start=1)
        )
    if item.kind is NativeExamItemKind.MATCHING and item.answer_key.match_pairs:
        left = {entry.left_id: body_plain_text(entry.body) for entry in item.match_left}
        right = {entry.right_id: body_plain_text(entry.body) for entry in item.match_right}
        return tuple(
            labels.keyed(labels.pair, f"{left[pair.left_id]} – {right[pair.right_id]}")
            for pair in item.answer_key.match_pairs
        )
    return ()
