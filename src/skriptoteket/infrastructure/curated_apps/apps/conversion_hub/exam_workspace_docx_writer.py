_ITEM_HEADING_STYLE = "Heading 3"
_MISSING_IMAGE_MESSAGE = "Word-exporten saknar bilddata för en bild."
NO_DOCX_EXPORT_ASSETS: Mapping[str, bytes] = MappingProxyType({})


class ExamWorkspaceDocxWriter:
    """Deterministic DOCX student copy rendered from the print document."""

    def build_docx_bytes(
        self,
        document: NativeExamDocument,
        *,
        assets_by_id: Mapping[str, bytes] = NO_DOCX_EXPORT_ASSETS,
    ) -> bytes:
        print_document = build_print_document(document, variant=ExamPrintVariant.STUDENT)
        output = Document()
        _apply_house_template(output)
        _PrintDocxRenderer(output, assets_by_id=assets_by_id).render(print_document)
        buffer = io.BytesIO()
        output.save(buffer)
        return buffer.getvalue()

    def validate_docx_bytes(self, content: bytes, *, expected_item_count: int) -> None:
        """Fail-closed D3 validation: the export must re-open and keep all items."""
        try:
            parsed = Document(io.BytesIO(content))
        except (
            PackageNotFoundError,
            zipfile.BadZipFile,
            KeyError,
            ValueError,
        ) as error:
            raise DomainError(
                code=ErrorCode.VALIDATION_ERROR,
                message="Det genererade Word-dokumentet kunde inte läsas.",
            ) from error
        heading_count = sum(
            1
            for paragraph in parsed.paragraphs
            if paragraph.style is not None and paragraph.style.name == _ITEM_HEADING_STYLE
        )
        if heading_count != expected_item_count:
            raise DomainError(
                code=ErrorCode.VALIDATION_ERROR,
                message="Det genererade Word-dokumentet saknar förväntade frågerubriker.",
                details={
                    "expected_item_count": expected_item_count,
                    "found_item_headings": heading_count,
                },
            )


class _PrintDocxRenderer:
    """One render pass of a print document into a python-docx document."""

    def __init__(self, output: DocxDocument, *, assets_by_id: Mapping[str, bytes]) -> None:
        self._output = output
        self._assets_by_id = assets_by_id
        self._last_paragraph: Paragraph | None = None
        self._after_grid = False

    def render(self, print_document: PrintDocument) -> None:
        for entry in print_document.entries:
            self._entry(entry)

    def _entry(self, entry: PrintInstruction | PrintQuestion) -> None:
        """Render one entry and give its last paragraph the entry's block spacing.

        A question or instruction closes with its own space after; a block's larger own
        space wins, as the print CSS's collapsed margins do.
        """
        blocks = entry.text + entry.answer if isinstance(entry, PrintQuestion) else entry.blocks
        for block in blocks:
            self._block(block)
        if isinstance(entry, PrintInstruction):
            space_after_mm = INSTRUCTION_SPACE_AFTER_MM
        else:
            space_after_mm = QUESTION_SPACE_AFTER_MM
        if isinstance(blocks[-1], PrintGrid):
            # A table has no paragraph spacing of its own: one exact-height spacer holds it.
            spacer = self._new_paragraph()
            spacer.paragraph_format.space_after = Pt(0)
            _set_exact_line_spacing(spacer, space_after_mm)
            return
        if self._last_paragraph is not None:
            _widen_space_after(self._last_paragraph, space_after_mm)

    def _block(self, block: PrintBlock) -> None:
        if isinstance(block, PrintHeading):
            self._heading(block)
        elif isinstance(block, PrintParagraph):
            self._paragraph(block)
        elif isinstance(block, PrintRuledLines):
            self._ruled_lines(block)
        elif isinstance(block, PrintOption):
            self._option(block)
        elif isinstance(block, PrintGrid):
            self._grid(block)
        elif isinstance(block, PrintAnswerKey):
            raise ValueError("the student copy never carries an answer key")
        else:
            raise AssertionError(f"unhandled print block: {type(block).__name__}")

    def _place(self, paragraph: Paragraph) -> Paragraph:
        """Track the newest paragraph and apply the grid's trailing space when it follows one."""
        if self._after_grid:
            paragraph.paragraph_format.space_before = Mm(GRID_SPACING.space_after_mm)
            self._after_grid = False
        self._last_paragraph = paragraph
        return paragraph

    def _new_paragraph(self) -> Paragraph:
        return self._place(self._output.add_paragraph())

    def _heading(self, block: PrintHeading) -> None:
        self._place(self._output.add_heading(block.text, level=block.level))

    def _paragraph(self, block: PrintParagraph) -> None:
        paragraph = self._new_paragraph()
        if block.style is PrintParagraphStyle.GAP_LINE:
            _set_exact_line_spacing(paragraph, WRITING_LINE_PITCH_MM)
        has_picture = False
        for run in block.runs:
            if isinstance(run, PrintText):
                paragraph.add_run(run.text)
            elif isinstance(run, PrintBlank):
                _add_blank(paragraph, run.width_mm)
            elif isinstance(run, PrintImage):
                has_picture = True
                self._picture(paragraph, run.asset_id)
            else:
                raise AssertionError(f"unhandled print run: {type(run).__name__}")
        _set_block_spacing(paragraph, IMAGE_SPACING if has_picture else PARAGRAPH_SPACING)

    def _ruled_lines(self, block: PrintRuledLines) -> None:
        for index in range(block.count):
            paragraph = self._new_paragraph()
            _add_ruled_line(
                paragraph,
                first=index == 0,
                last=index == block.count - 1,
            )

    def _option(self, option: PrintOption) -> None:
        paragraph = self._new_paragraph()
        _set_block_spacing(paragraph, OPTION_SPACING)
        if option.box is PrintBox.TICK:
            paragraph.add_run(TICK_BOX_GLYPH)
            label = f" {option.label}" if option.label else ""
            paragraph.add_run(f"{label} {option.text}")
            return
        if option.box is not PrintBox.NUMBER:
            raise AssertionError(f"unhandled print box: {option.box}")
        _add_number_box(paragraph)
        _add_box_gap(paragraph)
        paragraph.add_run(option.text)

    def _grid(self, grid: PrintGrid) -> None:
        if self._last_paragraph is not None:
            _widen_space_after(self._last_paragraph, GRID_SPACING.space_before_mm)
        table = self._output.add_table(rows=len(grid.rows) + 1, cols=len(grid.columns) + 1)
        table.style = "Table Grid"
        _set_cell_margins(table)
        header = table.rows[0].cells
        _set_cell_text(header[0], "")
        for index, column in enumerate(grid.columns, start=1):
            _set_cell_text(header[index], column)
        for row_index, row in enumerate(grid.rows, start=1):
            cells = table.rows[row_index].cells
            _set_cell_text(cells[0], row)
            for cell in cells[1:]:
                _set_cell_text(cell, TICK_BOX_GLYPH)
        self._after_grid = True
        self._last_paragraph = None

    def _picture(self, paragraph: Paragraph, asset_id: str) -> None:
        payload = self._assets_by_id.get(asset_id)
        if payload is None:
            raise _missing_image(asset_id)
        limit = Mm(TEXT_WIDTH_MM)
        native = _native_picture_width(payload)
        if native is None:
            # The pixel width is unknown: keep python-docx's own size unless it overflows.
            shape = paragraph.add_run().add_picture(io.BytesIO(payload))
            if shape.width is not None and shape.width > limit:
                shape.width = limit
            return
        paragraph.add_run().add_picture(io.BytesIO(payload), width=min(native, limit))


def _apply_house_template(output: DocxDocument) -> None:
    """The one house template: A4, the house font and every print style (W1, W3).

    No Word built-in layout default survives: the page, ``Normal`` and every declared
    heading level take their geometry from ``exam_print_house_template``.
    """
    for section in output.sections:
        section.page_width = Mm(PAGE_WIDTH_MM)
        section.page_height = Mm(PAGE_HEIGHT_MM)
        section.left_margin = Mm(PAGE_MARGIN_SIDE_MM)
        section.right_margin = Mm(PAGE_MARGIN_SIDE_MM)
        section.top_margin = Mm(PAGE_MARGIN_VERTICAL_MM)
        section.bottom_margin = Mm(PAGE_MARGIN_VERTICAL_MM)

    normal = output.styles["Normal"]
    _apply_house_font(normal)
    normal.font.size = Pt(HOUSE_FONT_SIZE_PT)
    normal.paragraph_format.line_spacing = HOUSE_LINE_HEIGHT
    _apply_house_text_color(normal)
    _set_style_spacing(normal.paragraph_format, PARAGRAPH_SPACING)

    for level, geometry in HEADING_GEOMETRY.items():
        heading = output.styles[f"Heading {level}"]
        _apply_house_font(heading)
        heading.font.size = Pt(geometry.size_pt)
        heading.font.bold = True
        heading.font.italic = False
        _apply_house_text_color(heading)
        _set_style_spacing(heading.paragraph_format, geometry.spacing)
        heading.paragraph_format.keep_with_next = True


def _apply_house_font(style: ParagraphStyle) -> None:
    """The house font on all four script slots, with every theme-font attribute removed."""
    style.font.name = HOUSE_FONT_FAMILIES[0]
    rPr = style.element.get_or_add_rPr()
    rFonts = rPr.find(qn("w:rFonts"))
    if rFonts is None:
        rFonts = OxmlElement("w:rFonts")
        rPr.insert(0, rFonts)
    for attribute in ("ascii", "hAnsi", "eastAsia", "cs"):
        rFonts.set(qn(f"w:{attribute}"), HOUSE_FONT_FAMILIES[0])
    for attribute in ("asciiTheme", "hAnsiTheme", "eastAsiaTheme", "cstheme"):
        rFonts.attrib.pop(qn(f"w:{attribute}"), None)


def _apply_house_text_color(style: ParagraphStyle) -> None:
    """The template's text colour, with the theme colour attributes removed."""
    style.font.color.rgb = RGBColor.from_string(TEXT_COLOR_HEX)
    color = style.element.get_or_add_rPr().find(qn("w:color"))
    if color is not None:
        for attribute in ("themeColor", "themeShade", "themeTint"):
            color.attrib.pop(qn(f"w:{attribute}"), None)


def _set_style_spacing(paragraph_format: ParagraphFormat, spacing: BlockSpacing) -> None:
    paragraph_format.space_before = Mm(spacing.space_before_mm)
    paragraph_format.space_after = Mm(spacing.space_after_mm)


def _set_block_spacing(paragraph: Paragraph, spacing: BlockSpacing) -> None:
    _set_style_spacing(paragraph.paragraph_format, spacing)


def _widen_space_after(paragraph: Paragraph, minimum_mm: float) -> None:
    """Raise a paragraph's space after to ``minimum_mm``; its own larger space wins."""
    current = paragraph.paragraph_format.space_after
    own_mm = 0.0 if current is None else current.mm
    if own_mm < minimum_mm:
        paragraph.paragraph_format.space_after = Mm(minimum_mm)


def _set_exact_line_spacing(paragraph: Paragraph, millimetres: float) -> None:
    fmt = paragraph.paragraph_format
    fmt.line_spacing = Mm(millimetres)
    fmt.line_spacing_rule = WD_LINE_SPACING.EXACTLY


def _add_ruled_line(paragraph: Paragraph, *, first: bool, last: bool) -> None:
    """One full-width ruled writing line (W9).

    The writing area's before/after margins sit on its first and last line. Word merges
    consecutive paragraphs that carry identical borders and draws only the group's outer
    edges, so each line owns both ``w:bottom`` and ``w:between``; the inner edge draws the
    line above the next ruled paragraph.
    """
    fmt = paragraph.paragraph_format
    fmt.space_before = Mm(WRITING_AREA_SPACING.space_before_mm if first else 0)
    fmt.space_after = Mm(WRITING_AREA_SPACING.space_after_mm if last else 0)
    _set_exact_line_spacing(paragraph, WRITING_LINE_PITCH_MM)
    pPr = paragraph._p.get_or_add_pPr()
    borders = OxmlElement("w:pBdr")
    for edge in ("w:bottom", "w:between"):
        border = OxmlElement(edge)
        border.set(qn("w:val"), "single")
        border.set(qn("w:sz"), _eighths_of_a_point(RULE_WEIGHT_PT))
        border.set(qn("w:space"), "0")
        border.set(qn("w:color"), RULE_COLOR_HEX)
        borders.append(border)
    spacing = pPr.find(qn("w:spacing"))
    if spacing is not None:
        spacing.addprevious(borders)
    else:
        pPr.append(borders)


def _add_blank(paragraph: Paragraph, width_mm: float) -> None:
    """An underlined handwriting blank: non-breaking spaces filling ``width_mm`` (W7)."""
    run = paragraph.add_run("\u00a0" * math.ceil(width_mm / NBSP_WIDTH_MM))
    run.font.underline = True
    underline = run._element.get_or_add_rPr().find(qn("w:u"))
    if underline is not None:
        underline.set(qn("w:color"), RULE_COLOR_HEX)


def _add_number_box(paragraph: Paragraph) -> None:
    """An empty bordered box one text line high: house-font spaces wide enough (W8)."""
    run = paragraph.add_run("\u00a0" * math.ceil(NUMBER_BOX_WIDTH_MM / NBSP_WIDTH_MM))
    rPr = run._element.get_or_add_rPr()
    border = OxmlElement("w:bdr")
    border.set(qn("w:val"), "single")
    border.set(qn("w:sz"), _eighths_of_a_point(BOX_BORDER_PT))
    border.set(qn("w:space"), "0")
    border.set(qn("w:color"), TEXT_COLOR_HEX)
    rPr.append(border)


def _add_box_gap(paragraph: Paragraph) -> None:
    """The gap between a box and its option text, rounded up to whole house-font spaces."""
    paragraph.add_run("\u00a0" * math.ceil(BOX_GAP_MM / NBSP_WIDTH_MM))


def _set_cell_margins(table: Table) -> None:
    """The template's cell padding on the matching grid."""
    tblPr = table._tbl.tblPr
    margins = OxmlElement("w:tblCellMar")
    for edge in ("top", "left", "bottom", "right"):
        measure = OxmlElement(f"w:{edge}")
        measure.set(qn("w:w"), str(_millimetres_to_twips(GRID_CELL_PADDING_MM)))
        measure.set(qn("w:type"), "dxa")
        margins.append(measure)
    tblPr.insert_element_before(margins, "w:tblLook", "w:tblCaption", "w:tblDescription")


def _set_cell_text(cell: _Cell, text: str) -> None:
    """One grid cell's text with no paragraph spacing of its own."""
    cell.text = text
    for paragraph in cell.paragraphs:
        _set_block_spacing(paragraph, BlockSpacing(0, 0))


def _eighths_of_a_point(points: float) -> str:
    """A border weight in the eighths of a point that ``w:sz`` expects."""
    return str(round(points * 8))


def _millimetres_to_twips(millimetres: float) -> int:
    return round(millimetres * 1440 / 25.4)


def _native_picture_width(payload: bytes) -> Length | None:
    try:
        return Image.from_blob(payload).width
    except UnrecognizedImageError:
        return None


def _missing_image(asset_id: str) -> DomainError:
    return DomainError(
        code=ErrorCode.VALIDATION_ERROR,
        message=_MISSING_IMAGE_MESSAGE,
        details={"asset_ids": [asset_id]},
    )
