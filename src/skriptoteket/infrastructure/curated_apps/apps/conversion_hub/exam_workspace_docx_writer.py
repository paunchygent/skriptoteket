"""DOCX student copy rendered from the format-neutral print document (TASK-SKRIPT-40-04-07).

The teacher's Word export is the student copy (W2): ``build_docx_bytes`` renders
``build_print_document(document, variant=ExamPrintVariant.STUDENT)`` in the one house
template and nothing else. The DOCX applies that template (W3): A4 with the template
margins, the house font, text colour, and every heading, block, answer-form and grid
dimension read from ``exam_print_house_template``; the print PDF/preview renders the
same template (W1, ruling 2026-10-18), so no renderer owns a second layout authority.
It prints ruled writing lines (W4, W9), a full-width line for a gap that stands alone in
its paragraph (W6), underlined handwriting blanks with writing-height spacing (W7), tick
boxes and empty number boxes (W8), and each question's pictures at their place; no
answer key or criterion ever reaches the copy. ``validate_docx_bytes`` re-opens the
generated bytes and fails closed before the artifact is handed out.
"""

